#!/usr/bin/env node

import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const tauriRoot = path.join(repoRoot, "src-tauri");

function readText(relativePath) {
  return fs.readFileSync(path.join(repoRoot, relativePath), "utf8");
}

function readJson(relativePath) {
  return JSON.parse(readText(relativePath));
}

function extractBlock(source, startMarker, endMarker, label) {
  const start = source.indexOf(startMarker);
  assert.notEqual(start, -1, `${label}: start marker is missing`);
  const contentStart = start + startMarker.length;
  const end = source.indexOf(endMarker, contentStart);
  assert.notEqual(end, -1, `${label}: end marker is missing`);
  return source.slice(contentStart, end);
}

function extractInvokeCommands(source) {
  const block = extractBlock(
    source,
    ".invoke_handler(tauri::generate_handler![",
    "])",
    "invoke handler",
  );
  return new Set(
    block
      .split(/\r?\n/u)
      .map((line) => line.split("//", 1)[0].trim())
      .filter(Boolean)
      .map((line) => line.replace(/,$/u, "").split("::").at(-1)),
  );
}

function extractBuildCommands(source) {
  const block = extractBlock(
    source,
    "const APP_COMMANDS: &[&str] = &[",
    "];",
    "build command manifest",
  );
  return new Set(
    [...block.matchAll(/"([a-z0-9_]+)"/gu)].map((match) => match[1]),
  );
}

function sorted(values) {
  return [...values].sort();
}

function permissionId(action, command) {
  return `${action}-${command.replaceAll("_", "-")}`;
}

function collectConstants(value, output = new Set()) {
  if (Array.isArray(value)) {
    for (const item of value) collectConstants(item, output);
  } else if (value && typeof value === "object") {
    if (typeof value.const === "string") output.add(value.const);
    for (const item of Object.values(value)) collectConstants(item, output);
  }
  return output;
}

const invokeCommands = extractInvokeCommands(readText("src-tauri/src/lib.rs"));
const buildCommands = extractBuildCommands(readText("src-tauri/build.rs"));
assert.deepEqual(
  sorted(invokeCommands),
  sorted(buildCommands),
  "src/lib.rs invoke handler and build.rs APP_COMMANDS must match",
);
assert.ok(buildCommands.size > 0, "APP_COMMANDS must not be empty");

const generatedPermissionCommands = new Set(
  fs
    .readdirSync(path.join(tauriRoot, "permissions", "autogenerated"))
    .filter((name) => name.endsWith(".toml"))
    .map((name) => name.slice(0, -".toml".length)),
);
assert.deepEqual(
  sorted(generatedPermissionCommands),
  sorted(buildCommands),
  "autogenerated permission file set must exactly match APP_COMMANDS",
);

const generatedCapabilities = readJson("src-tauri/gen/schemas/capabilities.json");
for (const name of ["default", "overlay", "tracking-panel"]) {
  const source = readJson(`src-tauri/capabilities/${name}.json`);
  const generated = generatedCapabilities[name];
  assert.ok(generated, `generated capability ${name} is missing`);
  assert.equal(generated.identifier, source.identifier, `${name} identifier is stale`);
  assert.equal(
    generated.description,
    source.description ?? "",
    `${name} description is stale`,
  );
  assert.deepEqual(generated.windows, source.windows, `${name} windows are stale`);
  assert.deepEqual(generated.permissions, source.permissions, `${name} permissions are stale`);
  assert.equal(generated.local, true, `${name} must remain local-only`);
}

const defaultPermissions = new Set(generatedCapabilities.default.permissions);
const acl = readJson("src-tauri/gen/schemas/acl-manifests.json");
const aclPermissions = acl["__app-acl__"]?.permissions;
assert.ok(aclPermissions, "generated app ACL permissions are missing");
const desktopSchema = readJson("src-tauri/gen/schemas/desktop-schema.json");
const macOSSchema = readJson("src-tauri/gen/schemas/macOS-schema.json");
const desktopConstants = collectConstants(desktopSchema);
const macOSConstants = collectConstants(macOSSchema);

// Tracked schemas use the webdriver superset so Tauri E2E permissions and
// production app commands share one reviewable generated contract.
// #9192: regenerate BOTH with the plugin feature enabled —
// `cargo check -p maekon-app --features webdriver`. A plain build silently
// drops the wdio permissions and produces a non-superset contract.
assert.deepEqual(
  macOSSchema,
  desktopSchema,
  "tracked macOS and desktop schemas must come from the same canonical webdriver build",
);
// #9192: the WDIO harness modernization (41ccc5b8cf) renamed the Tauri plugin
// `webdriver` -> `wdio`, but this validator kept asserting the old names while
// only desktop-schema/acl-manifests were regenerated. `acl.wdio` is the plugin
// carrying the six test-profile permissions; `acl["wdio-webdriver"]` is the
// bridge plugin and declares none.
assert.equal(
  acl.wdio?.default_permission?.identifier,
  "default",
  "canonical generated ACL must include the wdio test-profile permission",
);
for (const [name, constants] of [
  ["desktop", desktopConstants],
  ["macOS", macOSConstants],
]) {
  assert.ok(
    constants.has("wdio:default"),
    `${name} schema must include the canonical wdio test-profile permission`,
  );
}

for (const command of buildCommands) {
  const allow = permissionId("allow", command);
  const deny = permissionId("deny", command);
  assert.ok(defaultPermissions.has(allow), `default capability is missing ${allow}`);
  assert.ok(aclPermissions[allow], `generated ACL is missing ${allow}`);
  assert.ok(aclPermissions[deny], `generated ACL is missing ${deny}`);
  assert.ok(desktopConstants.has(allow), `desktop schema is missing ${allow}`);
  assert.ok(desktopConstants.has(deny), `desktop schema is missing ${deny}`);
  assert.ok(macOSConstants.has(allow), `macOS schema is missing ${allow}`);
  assert.ok(macOSConstants.has(deny), `macOS schema is missing ${deny}`);

  const permissionPath = path.join(
    tauriRoot,
    "permissions",
    "autogenerated",
    `${command}.toml`,
  );
  assert.ok(fs.existsSync(permissionPath), `generated permission file is missing: ${command}.toml`);
  const permissionSource = fs.readFileSync(permissionPath, "utf8");
  assert.match(permissionSource, new RegExp(`identifier = "${allow}"`, "u"));
  assert.match(permissionSource, new RegExp(`commands\\.allow = \\["${command}"\\]`, "u"));
  assert.match(permissionSource, new RegExp(`identifier = "${deny}"`, "u"));
  assert.match(permissionSource, new RegExp(`commands\\.deny = \\["${command}"\\]`, "u"));
}

process.stdout.write(
  `IPC command manifests and desktop/macOS schemas are synchronized (${buildCommands.size} commands, 3 capabilities).\n`,
);
